"""
Benchmark and test script for Piper TTS streaming playback vs batch synthesis.
Demonstrates ultra-low Time-To-First-Audio (TTFA) latency.
"""

import sys
import time
from pathlib import Path

# Add backend directory to path so 'src' imports resolve properly
BACKEND_DIR = Path(__file__).resolve().parent.parent
if str(BACKEND_DIR) not in sys.path:
    sys.path.insert(0, str(BACKEND_DIR))

from src.tts.synthesizer import TTSSynthesizer

def run_tts_benchmark():
    print("=" * 60)
    print("  Piper TTS Streaming vs Batch Playback Benchmark")
    print("=" * 60)

    print("[*] Initializing TTSSynthesizer (loading voice model)...")
    init_t0 = time.time()
    tts = TTSSynthesizer()
    print(f"[+] Loaded voice model in {time.time() - init_t0:.2f}s\n")

    test_sentences = [
        "Setting master volume to 50 percent now.",
        "Playing your requested song on YouTube in your default browser.",
        "Opening Visual Studio Code for you right away.",
    ]

    for idx, sentence in enumerate(test_sentences, 1):
        print(f"--- Test {idx}: \"{sentence}\" ---")

        # 1. Measure Batch Mode (synthesize whole buffer, then play)
        print(" [1] Batch mode (buffer full audio first)...")
        t0 = time.time()
        audio_arr, sr = tts.synthesize(sentence)
        synthesis_time = time.time() - t0
        print(f"     -> Full synthesis completed in: {synthesis_time:.3f}s (Audio samples: {len(audio_arr)})")

        # 2. Measure Streaming Mode (stream chunks directly to soundcard)
        print(" [2] Streaming mode (stream_speak live to sounddevice)...")
        t0 = time.time()
        # Measure time until the first chunk is generated by the engine
        first_chunk_time = None
        for chunk, rate in tts.synthesize_stream(sentence):
            first_chunk_time = time.time() - t0
            break
        print(f"     -> Time-to-First-Audio (TTFA): {first_chunk_time:.3f}s! (vs {synthesis_time:.3f}s full buffer)")

        print(" [3] Playing live via stream_speak()...")
        t_play = time.time()
        tts.speak(sentence, stream=True)
        print(f"     -> Playback finished in {time.time() - t_play:.2f}s\n")
        time.sleep(0.3)

    print("=" * 60)
    print("[SUCCESS] TTS Streaming Benchmark Complete!")
    print("=" * 60)

if __name__ == "__main__":
    run_tts_benchmark()
